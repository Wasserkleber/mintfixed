# Build a mintfixed executable and copy it under its exact release tag name.
# Cargo's binary remains target/release/mint.exe; this is an additional distributable.
# On untagged/modified source, use a dev filename instead of mislabelling a release.
# Run with: powershell -ExecutionPolicy Bypass -File .\scripts\build_tagged.ps1
# CI uses:  ./scripts/build_tagged.ps1 -NoBuild -Tag $env:MINTFIXED_RELEASE_TAG -OutputDirectory dist
param(
    [switch] $NoBuild,
    [string] $Tag = '',
    [string] $OutputDirectory = ''
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

# An explicit release tag must be a safe name, not an arbitrary filesystem path.
if ($Tag -and $Tag -notmatch '^(?:mintfixed_[a-zA-Z0-9][a-zA-Z0-9._-]*|v0\.2\.10-mintfixed-[0-9]+)$') {
    throw "Unsupported release tag: $Tag"
}

Push-Location $repo
try {
    if (-not $NoBuild) {
        $previousTag = $env:MINTFIXED_RELEASE_TAG
        try {
            if ($Tag) { $env:MINTFIXED_RELEASE_TAG = $Tag }
            & cargo build --release
            if ($LASTEXITCODE -ne 0) { throw "cargo build --release failed ($LASTEXITCODE)" }
        } finally {
            $env:MINTFIXED_RELEASE_TAG = $previousTag
        }
    }

    $binary = Join-Path $repo 'target\release\mint.exe'
    if (-not (Test-Path -LiteralPath $binary -PathType Leaf)) {
        throw "Missing compiled executable: $binary"
    }
    $versionLines = @(& $binary --version)
    if ($LASTEXITCODE -ne 0 -or $versionLines.Count -ne 1) {
        throw 'Cannot read compiled version from mint.exe --version'
    }
    $version = ([string]$versionLines[0]).Trim()

    # This matches the canonical CLI output generated by the shared build metadata.
    $number = '(?:0|[1-9][0-9]*)'
    $validRelease = '^mintfixed v(?<number>' + $number + '\.' + $number + '(?:\.' + $number + ')?(?:-[A-Za-z0-9]+(?:[.-][A-Za-z0-9]+)*)?)$'
    $releaseMatch = [regex]::Match($version, $validRelease)
    $legacyMatch = [regex]::Match($version, '^mintfixed (?<tag>v0\.2\.10-mintfixed-[0-9]+)$')

    if ($releaseMatch.Success) {
        $filenameTag = 'mintfixed_' + $releaseMatch.Groups['number'].Value
    } elseif ($legacyMatch.Success) {
        $filenameTag = $legacyMatch.Groups['tag'].Value
    } elseif ($version -match '^mintfixed (?:dev|v[0-9]+\.[0-9]+|0\.[0-9]+)') {
        $filenameTag = ''
    } else {
        throw "Unexpected CLI version output: $version"
    }

    if ($filenameTag) {
        # Even an exact version string must correspond to an actual tag on HEAD.
        $atTag = (& git rev-parse --verify "refs/tags/${filenameTag}^{commit}" 2>$null)
        $head = (& git rev-parse HEAD 2>$null)
        if ($LASTEXITCODE -ne 0 -or -not $atTag -or $atTag.Trim() -ne $head.Trim()) {
            throw "The compiled release label does not match an exact tag on HEAD: $filenameTag"
        }
    }
    if ($Tag) {
        if (-not $filenameTag -or $filenameTag -cne $Tag) {
            throw "Release tag $Tag does not match compiled binary: $version"
        }
    }

    if ($filenameTag) {
        $filename = "$filenameTag.exe"
    } else {
        # Preserve the fact that no exact release tag identifies this binary.
        $sha = (& git rev-parse --short=7 HEAD 2>$null)
        if ($LASTEXITCODE -ne 0 -or -not $sha) { $sha = 'unknown' }
        $suffix = if ($version.Contains('modified')) { '_modified' } else { '' }
        $filename = "mintfixed_dev_$($sha.Trim())$suffix.exe"
    }

    $destinationDirectory = if ($OutputDirectory) {
        if ([IO.Path]::IsPathRooted($OutputDirectory)) { $OutputDirectory }
        else { Join-Path $repo $OutputDirectory }
    } else { Join-Path $repo 'target\release' }
    New-Item -ItemType Directory -Path $destinationDirectory -Force | Out-Null
    $destination = Join-Path $destinationDirectory $filename
    Copy-Item -LiteralPath $binary -Destination $destination -Force

    Write-Host "Source version: $version"
    Write-Host "Tagged executable: $destination"
} finally {
    Pop-Location
}